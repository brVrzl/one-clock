#!/usr/bin/env python3
"""Generate display-only manuscript assets from the four frozen analyses."""

import json
import re
from pathlib import Path


PAPER_DIR = Path(__file__).resolve().parents[1]
REPO_DIR = PAPER_DIR.parents[1]
SOURCES = {
    "confirmation": REPO_DIR / "experiments/cross_suite_confirmation/analysis.json",
    "candidate1": REPO_DIR / "experiments/candidate1_c2_cross_suite/analysis.json",
    "object": REPO_DIR / "experiments/object_executor_decomposition/analysis.json",
    "posthoc": REPO_DIR / "experiments/posthoc_reporting/paired_completeness.json",
}
GENERATED_DIR = PAPER_DIR / "generated"


def load(path):
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def signed(value, digits=1):
    rendered = f"{value:+.{digits}f}"
    return rendered.replace("-0.0", "0.0")


def pp(value):
    return signed(100.0 * value)


def ci(interval):
    return f"[{pp(interval[0])},{pp(interval[1])}]"


def p_value(value):
    if value == 1:
        return "1"
    rendered = f"{value:.2e}" if value < 0.001 else f"{value:.3g}"
    if "e" not in rendered:
        return rendered
    mantissa, exponent = rendered.split("e")
    return rf"{mantissa}\times 10^{{{int(exponent)}}}"


def discordance(comparison):
    return f"{comparison['first_only_wins']}{{:}}{comparison['second_only_wins']}"


def macro(name, value):
    return rf"\newcommand{{\{name}}}{{{value}}}"


def contrast_macros(prefix, comparison, effect_key, discordance_key=True):
    lines = [
        macro(prefix + "Delta", signed(comparison[effect_key])),
        macro(prefix + "PairedCI", ci(comparison["paired_bootstrap_ci"])),
        macro(prefix + "ClusterCI", ci(comparison["task_cluster_bootstrap_ci"])),
        macro(prefix + "P", p_value(comparison["exact_two_sided_mcnemar_p"])),
    ]
    if discordance_key:
        lines.append(macro(prefix + "Discordance", discordance(comparison)))
    return lines


def figure_coordinate(value):
    # Fig. 1(c) maps the fixed -25..+50 pp axis to picture coordinates 0..75.
    return f"{value + 25.0:.3f}"


def main():
    data = {name: load(path) for name, path in SOURCES.items()}
    confirmation = data["confirmation"]
    candidate1 = data["candidate1"]
    obj = data["object"]
    posthoc = data["posthoc"]

    assert candidate1["claim_outcome"] == "OUTCOME_B"

    aggregate = {row["method"]: row for row in confirmation["primary_aggregate"]}
    primary = confirmation["primary_comparisons"]
    simple = posthoc["confirmation_factorial_simple_effects"]["comparisons"]
    interaction = posthoc["confirmation_factorial_interaction"]
    confirmation_pairwise = posthoc["confirmation_posthoc_pairwise"]
    candidate_comparisons = candidate1["comparisons"]
    object_c2 = obj["comparisons"]["C2_VS_FRESH"]
    object_hard_c2 = posthoc["object_development_posthoc"]["comparison"]

    source_comment = [
        "% Generated by scripts/generate_result_assets.py; do not edit.",
        "% Frozen JSON inputs:",
        *[f"% - {path.relative_to(REPO_DIR).as_posix()}" for path in SOURCES.values()],
        "",
    ]
    lines = list(source_comment)

    for method, prefix in [
        ("FRESH", "ConfirmFresh"),
        ("FO20", "ConfirmFO"),
        ("REVERSE20", "ConfirmReverse"),
        ("FULL_OLD20", "ConfirmFullOld"),
        ("HARD_H16", "ConfirmHard"),
    ]:
        row = aggregate[method]
        lines.extend(
            [
                macro(prefix + "Successes", row["successes"]),
                macro(prefix + "Blocks", row["blocks"]),
                macro(prefix + "Rate", f"{100.0 * row['success_rate']:.1f}"),
            ]
        )

    lines.append(macro("HardMeanSourceAge", f"{aggregate['HARD_H16']['observed_mean_gripper_source_age']:.1f}"))
    lines.append(macro("FreshOffset", int(aggregate["FRESH"]["observed_mean_gripper_source_age"])))

    primary_fo_reverse = primary["FO20_VS_REVERSE20"]
    lines.extend(
        contrast_macros(
            "ConfirmFOReverse",
            primary_fo_reverse,
            "success_delta_percentage_points",
        )
    )
    loto = primary_fo_reverse["leave_one_task_out"]
    lines.append(macro("ConfirmFOReverseLoto", f"{sum(row['delta'] > 0 for row in loto)}/{len(loto)}"))
    lines.extend(
        contrast_macros(
            "ConfirmFOFresh",
            primary["FO20_VS_FRESH"],
            "success_delta_percentage_points",
        )
    )
    lines.append(
        macro(
            "ConfirmFullOldFreshDelta",
            signed(posthoc["sanity_anchors"]["existing_primary_effects_percentage_points"]["FULL_OLD20_MINUS_FRESH"]),
        )
    )

    simple_effects = [
        ("PosthocArmFreshGrip", "ARM_WITH_FRESH_GRIPPER_REVERSE20_MINUS_FRESH"),
        ("PosthocArmOldGrip", "ARM_WITH_OLD_GRIPPER_FULL_OLD20_MINUS_FO20"),
        ("PosthocGripFreshArm", "GRIPPER_WITH_FRESH_ARM_FO20_MINUS_FRESH"),
        ("PosthocGripOldArm", "GRIPPER_WITH_OLD_ARM_FULL_OLD20_MINUS_REVERSE20"),
    ]
    for prefix, key in simple_effects:
        lines.extend(
            contrast_macros(
                prefix,
                simple[key],
                "effect_percentage_points",
            )
        )

    lines.extend(
        [
            macro("PosthocInteractionDelta", signed(interaction["interaction_percentage_points"])),
            macro("PosthocInteractionPairedCI", ci(interaction["paired_bootstrap_ci"])),
            macro("PosthocInteractionClusterCI", ci(interaction["task_cluster_bootstrap_ci"])),
        ]
    )

    for prefix, key in [
        ("PosthocHardFresh", "HARD_H16_MINUS_FRESH"),
        ("PosthocHardFO", "HARD_H16_MINUS_FO20"),
    ]:
        lines.extend(
            contrast_macros(
                prefix,
                confirmation_pairwise[key],
                "effect_percentage_points",
            )
        )

    lines.extend(
        contrast_macros(
            "ObjectCtwoFresh",
            object_c2,
            "success_delta_percentage_points",
        )
    )
    lines.extend(
        contrast_macros(
            "ObjectHardCtwo",
            object_hard_c2,
            "effect_percentage_points",
        )
    )
    lines.extend(
        contrast_macros(
            "ConfirmCtwoFresh",
            candidate_comparisons["C2_MINUS_FRESH"],
            "success_delta_percentage_points",
        )
    )
    lines.extend(
        [
            macro("ConfirmCtwoFreshDiscordantBlocks", candidate_comparisons["C2_MINUS_FRESH"]["discordant_blocks"]),
            macro("ConfirmCtwoFreshBlocks", candidate_comparisons["C2_MINUS_FRESH"]["blocks"]),
        ]
    )
    lines.extend(
        contrast_macros(
            "ConfirmHardCtwo",
            candidate_comparisons["HARD_H16_MINUS_C2"],
            "success_delta_percentage_points",
        )
    )
    robustness = posthoc["descriptive_robustness"]["HARD_H16_MINUS_C2_CONFIRMATION_LOTO"]
    lines.extend(
        [
            macro("ConfirmHardCtwoLoto", f"{robustness['leave_one_task_out_effects_positive']}/10"),
            macro("ConfirmHardCtwoLotoMinimum", pp(robustness["minimum_leave_one_task_out_effect"])),
        ]
    )

    delay_match = re.search(r"(\d+)$", primary_fo_reverse["first_method"])
    horizon_match = re.search(r"(\d+)$", aggregate["HARD_H16"]["method"])
    assert delay_match and horizon_match
    lines.extend(
        [
            macro("OldDelay", delay_match.group(1)),
            macro("HardHorizon", horizon_match.group(1)),
        ]
    )

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    (GENERATED_DIR / "result_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    figure_lines = list(source_comment)
    figure_contrasts = [
        ("ObjCtwo", object_c2, "success_delta_percentage_points"),
        ("ObjHardCtwo", object_hard_c2, "effect_percentage_points"),
        ("ConfCtwo", candidate_comparisons["C2_MINUS_FRESH"], "success_delta_percentage_points"),
        ("ConfHardCtwo", candidate_comparisons["HARD_H16_MINUS_C2"], "success_delta_percentage_points"),
    ]
    for prefix, comparison, effect_key in figure_contrasts:
        estimate = comparison[effect_key]
        low, high = (100.0 * value for value in comparison["paired_bootstrap_ci"])
        figure_lines.extend(
            [
                macro("Fig" + prefix + "Point", figure_coordinate(estimate)),
                macro("Fig" + prefix + "Low", figure_coordinate(low)),
                macro("Fig" + prefix + "High", figure_coordinate(high)),
                macro("Fig" + prefix + "Width", f"{high - low:.3f}"),
            ]
        )
    (GENERATED_DIR / "figure1_data.tex").write_text("\n".join(figure_lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
