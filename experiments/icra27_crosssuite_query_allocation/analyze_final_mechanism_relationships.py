#!/usr/bin/env python3
"""Apply the final frozen B1-derived and B3-to-R1 analyses."""

from __future__ import annotations

import csv
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SUPPLEMENT = ROOT.parent / "icra27_reviewer_supplement"
MAPPING = ((2, 2, 0.1), (4, 4, 0.2), (8, 8, 0.4), (12, 12, 0.6), (16, 16, 0.8), (20, 20, 1.0), (32, 32, 1.6))


def find_contrast(rows: list[dict], family: str, name: str) -> dict:
    matches = [row for row in rows if row["family"] == family and row["contrast"] == name]
    if len(matches) != 1:
        raise RuntimeError(f"expected one contrast {family}:{name}, got {len(matches)}")
    return matches[0]


def main() -> None:
    amendment = json.loads((ROOT / "final_analysis_only_amendment.json").read_text())
    timebase = (ROOT / "TEMPORAL_CONTRACT_AUDIT_SUPERSEDING_20260903.md").read_text()
    if amendment["status"] != "FROZEN_BEFORE_TRACK_A_CANONICAL_ANALYSIS_AND_REVIEWER_SUPPLEMENT_OUTCOMES":
        raise RuntimeError("analysis-only amendment drift")
    if "`offset/20`" not in timebase or "prior factor-two mapping is superseded" not in timebase:
        raise RuntimeError("B3/R1A time alignment is not identifiable")
    supplement = json.loads((SUPPLEMENT / "analysis.json").read_text())
    forecast = json.loads((ROOT / "track_b/forecast/analysis/summary.json").read_text())
    if supplement["status"] != "COMPLETE" or forecast["status"] != "COMPLETE":
        raise RuntimeError("canonical supplement or B3 analysis is incomplete")

    r1b = find_contrast(supplement["contrasts"], "r1b", "T20_R0_G0-T0_R20_G0")
    r1b_prediction = {
        "label": "B1_DERIVED_PROSPECTIVE_PREDICTION",
        "expected_direction": "T20_R0_G0-T0_R20_G0 >= 0",
        "observed": r1b,
        "status": "PASS" if r1b["delta_percentage_points"] >= 0 else "MECHANISM_DISSOCIATION",
    }

    rows = []
    act = forecast["policy_results"]["ACT"]
    for d, offset, seconds in MAPPING:
        arm = find_contrast(supplement["contrasts"], "r1a", f"A0_G0-A{d}_G0")
        gripper = find_contrast(supplement["contrasts"], "r1a", f"A0_G0-A0_G{d}")
        b3 = act[str(offset)]
        rows.append({
            "seconds": seconds,
            "r1a_source_age_steps_at_20hz": d,
            "b3_offset_steps_at_20hz": offset,
            "b3_arm_normalized_rmse": b3["groups"]["arm"]["rmse"],
            "b3_translation_normalized_rmse": b3["groups"]["translation"]["rmse"],
            "b3_rotation_normalized_rmse": b3["groups"]["rotation"]["rmse"],
            "b3_gripper_normalized_rmse": b3["groups"]["gripper"]["rmse"],
            "b3_gripper_native_sign_disagreement": b3["gripper_sign_disagreement"]["probability"],
            "r1a_fresh_minus_arm_stale_pp": arm["delta_percentage_points"],
            "r1a_fresh_minus_gripper_stale_pp": gripper["delta_percentage_points"],
        })

    output = {
        "status": "COMPLETE",
        "analysis_only_amendment": "e2fb21b",
        "timebase_audit": "SUPERSEDED_BY_TEMPORAL_CONTRACT_AUDIT_SUPERSEDING_20260903",
        "track_a_raw_outcomes_loaded": False,
        "r1b_prediction": r1b_prediction,
        "b3_r1a_characterization": {
            "status": "DESCRIPTIVE_CROSS_COHORT_NOT_SIGNIFICANCE_GATED",
            "interpolation": False,
            "matched_time_rows": rows,
        },
    }
    output_dir = ROOT / "track_b/final_mechanism_relationships"
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "summary.json").write_text(json.dumps(output, indent=2) + "\n")
    with (output_dir / "b3_r1a_matched_time.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader(); writer.writerows(rows)
    lines = [
        "# Final mechanism relationships", "",
        f"`B1_DERIVED_PROSPECTIVE_PREDICTION`: **{r1b_prediction['status']}**; observed translation-stale minus rotation-stale contrast `{r1b['delta_percentage_points']:+.2f}` pp.", "",
        "The B3-to-R1A table uses every frozen R1A age and exact matched physical times, without interpolation or lag selection. It is cross-cohort characterization, not a significance-gated mechanism test.", "",
        "See `b3_r1a_matched_time.csv` and `summary.json` for all values.", "",
    ]
    (output_dir / "report.md").write_text("\n".join(lines))
    figure = [
        "# Mechanism figure specification", "",
        "No artwork is generated by this analysis.", "",
        "Any later mechanism figure must use seconds as the primary horizontal axis, show every frozen R1A age, and show the full B3 offset grid in its canonical panel. The exact corrected matched-time correspondence is d20Hz={2,4,8,12,16,20,32} to k20Hz={2,4,8,12,16,20,32}.", "",
        "The figure must show ACT and SmolVLA together for same-target disagreement and forecastability, preserving the cross-policy dissociation. Persistence/dispersion may be presented as compatible characterization, not as a completed causal explanation.", "",
    ]
    (output_dir / "FIGURE_SPEC.md").write_text("\n".join(figure))
    print(json.dumps({"status": "COMPLETE", "r1b_prediction": r1b_prediction["status"]}, indent=2))


if __name__ == "__main__":
    main()
